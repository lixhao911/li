using System;
using System.Collections.Generic;
using System.Globalization;
using PrinterUpperComputer.Model;

namespace PrinterUpperComputer.Services
{
    /// <summary>
    /// 切片参数（界面上的两个数值框最终填到这里）。
    /// </summary>
    public class SlicerSettings
    {
        /// <summary>层厚 mm（每层打印厚度，越小越精细、耗时越长）</summary>
        public double LayerHeight = 0.2;

        /// <summary>填充线间距 mm（相邻两条填充线中心距，越小越密实）</summary>
        public double InfillSpacing = 1.0;

        /// <summary>线宽 mm（喷嘴直径附近取值，用于计算挤出量）</summary>
        public double LineWidth = 0.4;

        /// <summary>耗材直径 mm（PLA 常见 1.75）</summary>
        public double FilamentDiameter = 1.75;

        /// <summary>打印进给速度 mm/min（G1 的 F 值）</summary>
        public double PrintSpeed = 1500;

        /// <summary>空走速度 mm/min（G0 的 F 值）</summary>
        public double TravelSpeed = 3000;
    }

    /// <summary>
    /// 教学级切片引擎（纯 C# 自写开源实现，无外部进程依赖）。
    ///
    /// 切片原理（三步）：
    /// 1) 对每一层高度 z，用水平面 z=常数 去切每个三角形。
    ///    三角形与平面要么不相交，要么交出一条线段（平面过顶点/边时按半开规则处理）。
    /// 2) 该层所有线段首尾相接，拼成若干闭合“轮廓环”（岛屿）。
    /// 3) 对每个环做扫描线填充：水平线与环边求交，交点两两配对即内部区间，
    ///    在区间内走往复直线（zigzag），按走过的长度换算挤出机 E 值。
    ///
    /// 局限（教学用途，已在 README 说明）：不做支撑生成、不区分内外墙、
    /// 不做顶层/底层实心填充、孔洞岛屿不做布尔扣减。
    /// 生产级切片可在本类位置替换为 CuraEngine/Slic3r 的命令行封装，输出仍为 G 代码，
    /// 下游（表格、PLC 发送）完全不用改。
    /// </summary>
    public static class Slicer
    {
        public static List<GCodeCommand> Slice(Mesh mesh, SlicerSettings s)
        {
            return new SlicContext(mesh, s).Run();
        }

        // ------------------------------------------------------------------
        // 一次切片任务的上下文（保存行号、当前坐标、累计挤出量等状态）
        // ------------------------------------------------------------------
        private class SlicContext
        {
            private readonly Mesh _mesh;
            private readonly SlicerSettings _s;
            private readonly List<GCodeCommand> _rows = new List<GCodeCommand>();

            private int _lineNo;          // 当前已生成行号
            private double _e;            // 累计挤出量 E（绝对值）
            private double _curX, _curY, _curZ = double.NaN; // 喷头当前位置
            private bool _printSpeedSet;  // F1500 是否已给过一次

            // 耗材截面积（用于把“走过的路径长度”换算成进料长度）
            private readonly double _filamentArea;

            public SlicContext(Mesh mesh, SlicerSettings s)
            {
                _mesh = mesh;
                _s = s;
                _filamentArea = Math.PI * s.FilamentDiameter * s.FilamentDiameter / 4.0;
            }

            public List<GCodeCommand> Run()
            {
                // ---------------- 文件头 ----------------
                AddRaw("; ============================================================");
                AddRaw("; G-code generated by PrinterUpperComputer (C# teaching slicer)");
                AddRaw("; source : " + _mesh.SourceFile);
                AddRaw(string.Format(CultureInfo.InvariantCulture,
                    "; triangles: {0}, size: {1}", _mesh.Triangles.Count, _mesh.SizeText));
                AddRaw(string.Format(CultureInfo.InvariantCulture,
                    "; layer height: {0:0.###} mm, infill spacing: {1:0.###} mm",
                    _s.LayerHeight, _s.InfillSpacing));
                AddRaw("; ============================================================");
                AddRaw("G21      ; set units to millimeters");
                AddRaw("G90      ; absolute positioning");
                AddRaw("G92 E0   ; reset extruder position");

                // ---------------- 逐层切片 ----------------
                double minZ = _mesh.Min.Z;
                double maxZ = _mesh.Max.Z;
                int layerCount = Math.Max(1,
                    (int)Math.Ceiling((maxZ - minZ) / _s.LayerHeight - 1e-9));

                for (int li = 0; li < layerCount; li++)
                {
                    // 该层所在高度（取每层上表面）
                    double z = minZ + _s.LayerHeight * (li + 1);

                    // 第 1 步：水平面切三角形，得到线段
                    List<Segment2> segments = IntersectLayer(z);

                    // 第 2 步：线段拼成轮廓环
                    List<List<Vec2>> loops = BuildLoops(segments);

                    AddRaw("; ------------------------------------------------------------");
                    AddRaw(string.Format(CultureInfo.InvariantCulture,
                        "; layer {0}/{1}, Z={2:0.###}, loops={3}",
                        li + 1, layerCount, z, loops.Count));

                    // 抬升/下降到本层高度
                    if (Math.Abs(_curZ - z) > 1e-6 || double.IsNaN(_curZ))
                    {
                        AddRaw(string.Format(CultureInfo.InvariantCulture,
                            "G0 Z{0:0.###} F{1:0}", z, _s.TravelSpeed));
                        _curZ = z;
                    }

                    // 第 3 步：先画轮廓（外墙），再做扫描线填充
                    foreach (List<Vec2> loop in loops)
                        EmitPerimeter(loop);

                    foreach (List<Vec2> loop in loops)
                        EmitInfill(loop);
                }

                // ---------------- 文件尾 ----------------
                AddRaw("; ------------------------------------------------------------");
                AddRaw("; print finished");
                AddRaw(string.Format(CultureInfo.InvariantCulture,
                    "; total extrusion E={0:0.#####}", _e));
                AddRaw("; M84    ; uncomment to disable motors if your printer supports it");

                return _rows;
            }

            // //////////////////////////////////////////////////////////////////
            // 第 1 步：水平面 z 与所有三角形求交
            // //////////////////////////////////////////////////////////////////
            private List<Segment2> IntersectLayer(double z)
            {
                var result = new List<Segment2>();
                const double eps = 1e-6;

                foreach (Triangle t in _mesh.Triangles)
                {
                    var hits = new List<Vec3>();

                    // 对一条边 p→q：当且仅当一个端点在平面下方、另一个在平面上/上方时求交。
                    // 这是“半开区间”规则，可保证平面过顶点时交点不会被相邻三角形重复计算。
                    void Edge(Vec3 p, Vec3 q)
                    {
                        bool pBelow = p.Z < z - eps;
                        bool qBelow = q.Z < z - eps;
                        if (pBelow != qBelow)
                        {
                            double tt = (z - p.Z) / (q.Z - p.Z);
                            tt = Math.Max(0, Math.Min(1, tt)); // 数值保护，夹到 [0,1]
                            hits.Add(new Vec3(
                                (float)(p.X + (q.X - p.X) * tt),
                                (float)(p.Y + (q.Y - p.Y) * tt),
                                (float)z));
                        }
                    }

                    Edge(t.A, t.B);
                    Edge(t.B, t.C);
                    Edge(t.C, t.A);

                    if (hits.Count >= 2)
                    {
                        var a = new Vec2(hits[0].X, hits[0].Y);
                        var b = new Vec2(hits[1].X, hits[1].Y);
                        if (Distance(a, b) > eps) result.Add(new Segment2(a, b));
                    }
                    else if (Math.Abs(t.A.Z - z) <= eps &&
                             Math.Abs(t.B.Z - z) <= eps &&
                             Math.Abs(t.C.Z - z) <= eps)
                    {
                        // 三角形整体恰好躺在该平面上（平顶/平底）：三条边直接加入
                        result.Add(new Segment2(new Vec2(t.A.X, t.A.Y), new Vec2(t.B.X, t.B.Y)));
                        result.Add(new Segment2(new Vec2(t.B.X, t.B.Y), new Vec2(t.C.X, t.C.Y)));
                        result.Add(new Segment2(new Vec2(t.C.X, t.C.Y), new Vec2(t.A.X, t.A.Y)));
                    }
                }
                return result;
            }

            // //////////////////////////////////////////////////////////////////
            // 第 2 步：把零散线段贪心连接成闭合环
            // //////////////////////////////////////////////////////////////////
            private List<List<Vec2>> BuildLoops(List<Segment2> segments)
            {
                var loops = new List<List<Vec2>>();
                var unused = new List<Segment2>(segments);
                const double tol = 1e-4;

                while (unused.Count > 0)
                {
                    // 从第一条线段开始生长
                    var loop = new List<Vec2> { unused[0].A, unused[0].B };
                    unused.RemoveAt(0);

                    bool changed = true;
                    while (changed)
                    {
                        changed = false;
                        Vec2 head = loop[0];
                        Vec2 tail = loop[loop.Count - 1];

                        for (int i = 0; i < unused.Count; i++)
                        {
                            Segment2 s = unused[i];

                            // 接到环尾
                            if (Distance(s.A, tail) <= tol)
                            { loop.Add(s.B); unused.RemoveAt(i); changed = true; break; }
                            if (Distance(s.B, tail) <= tol)
                            { loop.Add(s.A); unused.RemoveAt(i); changed = true; break; }

                            // 接到环头（注意方向要反过来插）
                            if (Distance(s.B, head) <= tol)
                            { loop.Insert(0, s.A); unused.RemoveAt(i); changed = true; break; }
                            if (Distance(s.A, head) <= tol)
                            { loop.Insert(0, s.B); unused.RemoveAt(i); changed = true; break; }
                        }
                    }

                    // 首尾重合则去掉重复的尾点，形成真正的闭合环
                    if (loop.Count > 1 && Distance(loop[0], loop[loop.Count - 1]) < tol)
                        loop.RemoveAt(loop.Count - 1);

                    loops.Add(loop);
                }
                return loops;
            }

            // //////////////////////////////////////////////////////////////////
            // 轮廓（外墙）：空走到起点，然后沿环走一圈，全程出料
            // //////////////////////////////////////////////////////////////////
            private void EmitPerimeter(List<Vec2> loop)
            {
                if (loop.Count < 2) return;

                Vec2 start = loop[0];
                TravelTo(start.X, start.Y); // G0 抬笔移动到起点

                for (int i = 1; i <= loop.Count; i++)
                {
                    Vec2 p = i == loop.Count ? loop[0] : loop[i]; // 最后回到起点闭合
                    ExtrudeTo(p.X, p.Y);                          // G1 出料
                }
            }

            // //////////////////////////////////////////////////////////////////
            // 第 3 步：扫描线 zigzag 填充
            // //////////////////////////////////////////////////////////////////
            private void EmitInfill(List<Vec2> loop)
            {
                if (loop.Count < 3) return; // 开放折线无法填充

                double minY = double.MaxValue, maxY = double.MinValue;
                foreach (Vec2 p in loop)
                {
                    if (p.Y < minY) minY = p.Y;
                    if (p.Y > maxY) maxY = p.Y;
                }

                int lineIndex = 0; // 往复方向按扫描线序号奇偶切换

                for (double y = minY + _s.InfillSpacing / 2.0;
                     y < maxY;
                     y += _s.InfillSpacing)
                {
                    var xs = new List<double>();

                    // 求扫描线 y 与环每条边的交点（标准多边形半开规则，凹多边形也正确）
                    for (int i = 0; i < loop.Count; i++)
                    {
                        Vec2 p = loop[i];
                        Vec2 q = loop[(i + 1) % loop.Count];

                        if ((p.Y > y) != (q.Y > y))
                        {
                            double t = (y - p.Y) / (q.Y - p.Y);
                            xs.Add(p.X + (q.X - p.X) * t);
                        }
                    }

                    xs.Sort();

                    // 交点两两配对：[0,1]、[2,3]... 每对之间是多边形内部
                    for (int k = 0; k + 1 < xs.Count; k += 2)
                    {
                        double x0 = xs[k];
                        double x1 = xs[k + 1];

                        if (lineIndex % 2 == 1) { double tmp = x0; x0 = x1; x1 = tmp; }

                        TravelTo(x0, y);   // 空走到本根填充线起点
                        ExtrudeTo(x1, y);  // 出料画到终点
                        lineIndex++;
                    }
                }
            }

            // //////////////////////////////////////////////////////////////////
            // 运动指令生成小工具
            // //////////////////////////////////////////////////////////////////

            /// <summary>G0 快速空走（不出料），只输出发生变化的轴。</summary>
            private void TravelTo(double x, double y)
            {
                if (Math.Abs(_curX - x) < 1e-6 && Math.Abs(_curY - y) < 1e-6) return;

                AddRaw(string.Format(CultureInfo.InvariantCulture,
                    "G0 X{0:0.###} Y{1:0.###} F{2:0}", x, y, _s.TravelSpeed));
                _curX = x;
                _curY = y;
            }

            /// <summary>G1 出料直线：按路径长度换算进料长度，累加到 E。</summary>
            private void ExtrudeTo(double x, double y)
            {
                double len = Math.Sqrt((x - _curX) * (x - _curX) +
                                       (y - _curY) * (y - _curY));
                // 路径体积 = 线宽×层厚×长度；进料长度 = 体积 ÷ 耗材截面积
                _e += len * _s.LineWidth * _s.LayerHeight / _filamentArea;

                string line = string.Format(CultureInfo.InvariantCulture,
                    "G1 X{0:0.###} Y{1:0.###} E{2:0.#####}", x, y, _e);

                // 打印速度只在第一条 G1 上给一次（G 代码模态，后续保持）
                if (!_printSpeedSet)
                {
                    line += string.Format(CultureInfo.InvariantCulture,
                        " F{0:0}", _s.PrintSpeed);
                    _printSpeedSet = true;
                }

                AddRaw(line);
                _curX = x;
                _curY = y;
            }

            /// <summary>加一行原始文本，并立即解析（生成的 G 代码自带结构化坐标）。</summary>
            private void AddRaw(string raw)
            {
                _rows.Add(GCodeCommand.Parse(++_lineNo, raw));
            }

            private static double Distance(Vec2 a, Vec2 b)
            {
                double dx = a.X - b.X;
                double dy = a.Y - b.Y;
                return Math.Sqrt(dx * dx + dy * dy);
            }
        }
    }
}
